export function getRandomQuizQuestions(count = 5, targetLanguages = []) {
  // Filter questions to only those matching the user's selected languages
  let pool = ALL_QUIZ_QUESTIONS;
  if (targetLanguages && targetLanguages.length > 0) {
    const filtered = ALL_QUIZ_QUESTIONS.filter(q => targetLanguages.includes(q.language));
    // Use filtered pool if it has enough questions, otherwise fall back to all
    if (filtered.length >= count) {
      pool = filtered;
    }
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

